// Runs after `next build` (npm "postbuild").
// Hashes every inline <script> in the static export and writes the nginx CSP include,
// so the Content-Security-Policy can drop 'unsafe-inline' for scripts.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const OUT = "out";
const TARGET = "deploy/pravadhdocsign-csp.inc";

const html = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (p.endsWith(".html")) html.push(p);
  }
})(OUT);

const hashes = new Set();
const inline = /<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g;
for (const file of html) {
  const text = readFileSync(file, "utf8");
  for (const m of text.matchAll(inline)) {
    if (m[1]) hashes.add(`'sha256-${createHash("sha256").update(m[1]).digest("base64")}'`);
  }
}

const csp = [
  "default-src 'self'",
  `script-src 'self' https://www.googletagmanager.com https://*.googletagmanager.com https://googleads.g.doubleclick.net https://www.googleadservices.com ${[...hashes].sort().join(" ")}`,
  "style-src 'self' 'unsafe-inline'",
  "font-src 'self'",
  "img-src 'self' data: https://*.google-analytics.com https://*.googletagmanager.com https://*.google.com https://*.doubleclick.net https://*.googlesyndication.com https://www.googleadservices.com",
  "connect-src 'self' https://*.google-analytics.com https://*.analytics.google.com https://*.googletagmanager.com https://*.google.com https://*.doubleclick.net https://*.googlesyndication.com https://www.googleadservices.com",
  "manifest-src 'self'",
  "frame-src https://*.doubleclick.net https://www.googletagmanager.com",
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "object-src 'none'",
  "upgrade-insecure-requests",
].join("; ");

writeFileSync(
  TARGET,
  `# Generated by scripts/gen-csp.mjs on build — do not edit by hand.\n` +
    `add_header Content-Security-Policy "${csp}" always;\n`,
);
console.log(`CSP: ${hashes.size} inline script hashes from ${html.length} pages -> ${TARGET}`);
